"""Report Generation Agent: Converts validated findings into structured Markdown/PDF reports."""
from typing import Dict, Any, List
from app.agents.state import AURAState


class ReportGenerationAgent:
    @staticmethod
    async def run(state: AURAState) -> Dict[str, Any]:
        """Synthesize structured report with Executive Summary, Findings, Risks, and Citations."""
        query = state.get("query", "")
        findings = state.get("research_findings", [])
        insights = state.get("analytical_insights", [])
        entities = state.get("extracted_entities", [])
        citations = state.get("citations", [])

        # Executive Summary
        summary = (
            f"This intelligence assessment was autonomously generated by AURA in response to: "
            f"\"{query}\". The analysis evaluates {len(findings)} source evidence sections, "
            f"synthesizing verified facts, identified constraints, and operational risks."
        )

        # Markdown Report Construction
        lines = [
            f"# AURA Assessment & Intelligence Report",
            f"**Objective**: {query}\n",
            f"## 1. Executive Summary",
            f"{summary}\n",
            f"## 2. Evidence & Key Findings"
        ]

        for idx, f in enumerate(findings[:4], 1):
            src = f.get("source", "Document")
            loc = f": Page {f.get('page')}" if f.get("page") else ""
            lines.append(f"### Finding 2.{idx}: [{src}{loc}]")
            lines.append(f"> \"{f.get('evidence', '')[:250].strip()}...\"\n")

        lines.append("## 3. Analytical Synthesis & Gap Analysis")
        for ins in insights:
            lines.append(f"- **{ins.get('category')} - {ins.get('title')}**: {ins.get('detail')} *(Confidence: {int(ins.get('confidence', 0.9)*100)}%)*")

        if entities:
            lines.append("\n## 4. Extracted Requirements & Constraints")
            for ent in entities[:5]:
                lines.append(f"- `[{ent.get('entity_type')}]` **{ent.get('name')}** (Source: {ent.get('source')})")

        lines.append("\n## 5. Risk Assessment & Recommendations")
        lines.append("- **Risk 1**: Ensure test suites cover all newly identified requirement constraints before production rollout.")
        lines.append("- **Recommendation**: Schedule verification of cross-document dependencies identified in Section 3.")

        lines.append("\n## 6. Citations & Evidentiary Traceability")
        for c in citations:
            p_str = f", Page {c.get('page_number')}" if c.get('page_number') else ""
            lines.append(f"- **{c.get('document_title')}{p_str}**: `{c.get('excerpt', '')[:120]}...`")

        final_report_md = "\n".join(lines)

        plan_steps = state.get("plan_steps", [])
        for step in plan_steps:
            if step.get("agent") == "report_generation":
                step["status"] = "completed"

        return {
            "final_response": final_report_md,
            "plan_steps": plan_steps,
            "current_step_name": "Report Generation Completed"
        }
